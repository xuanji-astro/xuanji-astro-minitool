// birthY：那一年 22 岁及以下用学业版（干表、领域句都换学业那一套；「动的是」不报工作）
function yearItem(dm, y, lights, birthY) {
  const gz = ganzhiOf(y), tg = tenGod(dm, gz[0]), tz = tenGod(dm, MAINQI[gz[1]]);
  const cg = CAT[tg], cz = CAT[tz], fuG = FU.has(cg), fuZ = FU.has(cz);
  const eg = elG(gz[0]), ez = elG(MAINQI[gz[1]]);
  const clash = KE[eg] === ez || KE[ez] === eg;   // 干支互克＝混杂年
  const verbs = VERB_ORDER.filter((v) => v === VERB[cg] || v === VERB[cz]).join('');
  const els = [...new Set([eg, ez])].join('');
  const study = !!birthY && y - birthY < RULES.workAge;
  const focus = Object.entries(lights || {}).filter(([k, v]) => DOMAIN_WORD[k] && v && v.w >= LIT && !(study && k === '工作')).sort((a, b) => b[1].w - a[1].w).map(([k]) => k);
  const line = (side) => ((focus[0] && (study ? DOMAIN_LINE_STUDY : DOMAIN_LINE)[cg][focus[0]]) || (study ? GAN_LINE_STUDY : GAN_LINE)[cg])[side];
  return {
    year: y, gan_zhi: gz, gan_god: tg, zhi_god: tz, context: study ? '学业' : '职场',
    kind: fuG && fuZ ? '扶' : !fuG && !fuZ ? '耗' : '背离',
    pure: fuG === fuZ && !clash,
    typical: (cg === '印' && cz === '比劫') || (cg === '比劫' && cz === '印') || (cg === '财' && cz === '官杀') || (cg === '官杀' && cz === '财'),
    head: `${tg}透干、${tz}坐支 · ${els}${verbs}日主${dm}${elG(dm)}`,
    focus: focus.slice(0, 2).map((k) => DOMAIN_WORD[k]), lit: focus.length ? Math.max(...focus.map((k) => lights[k].w)) : 0,
    readings: { 弱: `${line('弱')}；${ZHI_LINE[cz].弱}`, 强: `${line('强')}；${ZHI_LINE[cz].强}` },
    order: (hash(dm + y) & 1) ? ['强', '弱'] : ['弱', '强'],   // 单独取一年时的先后；出题时 feelAsk 再按题序交替
  };
}

// 挑年：近 span 年、约 15 岁起（记得清）、干支纯年；扶、耗两类都要有；同类里先挑这个人那年真被引动过的（记得清），再挑典型组合，再按近
// years＝时间线引擎的逐年结果（有就按各人盘里的亮灯挑年、写描述）
function feelAsk(dm, nowY, birthY, years) {
  const L = new Map((years || []).map((r) => [r.year, r.bazi]));
  const pool = [], mixed = [];
  for (let y = nowY - 1; y >= nowY - RULES.span; y--) {
    if (birthY && y - birthY < RULES.minAge) continue;
    const it = yearItem(dm, y, L.get(y), birthY);
    if (it.pure) pool.push(it); else if (it.kind === '背离') mixed.push(it);   // 背离年：干扶支耗或反过来，只在加问时纯年不够才用
  }
  const rank = (a, b) => ((b.lit > 0) - (a.lit > 0)) || (b.typical - a.typical) || (b.lit - a.lit) || (b.year - a.year);
  const fu = pool.filter((x) => x.kind === '扶').sort(rank), hao = pool.filter((x) => x.kind === '耗').sort(rank);
  // 凑不满三个记得清的对照年（太小、经历太薄，或近几年没有纯年）就不出题，不对小孩硬出题（10-05 定）；界面说「等经历再多一些，随时可以回来核」
  const young = !!birthY && nowY - RULES.span < birthY + RULES.minAge;   // 年龄线切掉了窗口里的年份
  const short = (why) => ({ enough: false, young, why, template: TEMPLATE });
  if (!fu.length || !hao.length) return short(!pool.length ? '近几年没有干支纯年' : '近几年只有' + (fu.length ? '帮身' : '耗身') + '的纯年，缺另一类对照');
  if (pool.length < RULES.first) return short('近几年能拿来对照的年份不够三个');
  const first = [fu[0], hao[0]];
  const rest = [...fu.slice(1), ...hao.slice(1)].sort(rank);
  first.push(rest.shift());
  first.sort((a, b) => b.year - a.year);
  // 同一组题里两种读法的先后交替出现（起头按日主定），免得「选第一个」就是同一种读法
  const s0 = hash(dm) & 1;
  // 加问先用剩下的纯年，不够再用背离年（身弱读法＝事顺心累，身强读法＝事被按住心舒展）
  const extra = [...rest, ...mixed.sort((a, b) => ((b.lit > 0) - (a.lit > 0)) || (b.lit - a.lit) || (b.year - a.year))];
  [...first, ...extra].forEach((x, i) => { x.order = (i + s0) % 2 ? ['强', '弱'] : ['弱', '强']; });
  return {
    enough: true, rules: RULES, template: TEMPLATE,
    first_ask: first,
    extra,
  };
}

// 计分：answers＝[{ year, dm, pick: '弱'|'强'|'都沾'|'记不清' }]，可以是好几次核的累积
function feelScore(dm, answers, ask) {
  const last = new Map();
  for (const a of answers || []) if (a && a.dm === dm && a.year) last.set(a.year, a.pick);   // 日主变了的旧回答不算；同一年以最后一次为准
  const n = { 弱: 0, 强: 0, 都沾: 0, 记不清: 0 };
  for (const p of last.values()) if (p in n) n[p]++;
  const asked = last.size, sides = { 弱: n.弱, 强: n.强 };
  const win = sides.弱 >= RULES.decideMin && sides.强 === 0 ? '弱' : sides.强 >= RULES.decideMin && sides.弱 === 0 ? '强' : null;
  if (win) return { status: '定案', decided: win, counts: n, asked };
  const next = ask && ask.enough ? [...ask.first_ask, ...ask.extra].find((x) => !last.has(x.year)) : null;
  if (asked < RULES.max && next) return { status: '加问', decided: null, counts: n, asked, next };
  return { status: '挂起', decided: null, counts: n, asked, why: sides.弱 || sides.强 ? '两种读法都有对上的年份，拉不开' : '都没选出哪一种，体感不可判' };
}

module.exports = { feelAsk, feelScore, yearItem, tenGod, hash, RULES, TEMPLATE };
