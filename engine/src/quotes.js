const hash = (str) => { let h = 0x811c9dc5; for (const ch of String(str)) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; } return h; };

// 每个用途挑一句：同主题里按生辰种子取，前面挑过的不再挑；今年顺逆决定流年那两句的主题
function pickQuotes(seed, tier) {
  const yearThemes = tier == null ? ['转折', '坚持'] : tier >= 3 ? ['蛰伏', '坚持'] : tier <= 1 ? ['突破', '转折'] : ['转折', '坚持'];
  const slots = [['流年', yearThemes[0]], ['流年', yearThemes[1]], ['事业', '事业'], ['财富', '财富'], ['感情', '感情'], ['家庭', '家庭'], ['社交', '社交'], ['健康', '健康'], ['学习与成长', '自我'], ['学习与成长', '学习']];
  const used = new Set(), out = [];
  for (const [use, theme] of slots) {
    const pool = LIB.filter((q) => q.themes.includes(theme) && !used.has(q.text));
    if (!pool.length) continue;
    const q = pool[hash(seed + '|' + use + '|' + theme) % pool.length];
    used.add(q.text); out.push({ use, text: q.text, source: q.source });
  }
  return out;
}

